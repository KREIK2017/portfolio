"use client";

import { usePrefersReducedMotion } from "@/lib/hooks";

/**
 * Фільтр «жива олія»: шум зсуває пікселі полотна, і мазки тремтять —
 * ніби фарба ще не висохла.
 *
 * Фільтр один на всі картки, і це принципово. Раніше їх було два —
 * слабший для спокою й сильніший під курсором, — але CSS не вміє
 * інтерполювати між двома url()-фільтрами: при наведенні граф просто
 * миттєво підмінявся, ще й на випадковій фазі власного таймлайна.
 * Тому підсвічування картки тепер робиться яскравістю в CSS, яку
 * браузер уміє плавно проганяти.
 *
 * Три речі відповідають за те, щоб зсув не сипався сходинками. Браузер
 * растеризує область SVG-фільтра в обмеженій роздільності й розтягує
 * результат під HiDPI-екран — саме звідси береться «пісок»:
 *
 * 1. feGaussianBlur між шумом і зсувом розмиває карту зсуву, тому
 *    сусідні пікселі їдуть майже однаково. Найдієвіший із трьох.
 * 2. Малий scale: артефакти ростуть прямо пропорційно амплітуді.
 * 3. numOctaves={1}: другий шар шуму додає дрібну деталь, яку фільтр
 *    у своїй роздільності однаково не відтворює — вона й перетворюється
 *    на зернистість.
 *
 * При prefers-reduced-motion вузол <animate> не рендериться взагалі.
 * Підхід «поставити dur у 999999s» руху не зупиняє: значення
 * продовжує інтерполюватися, а фільтр — перемальовуватися.
 */
export function LivingOilFilter() {
  const reducedMotion = usePrefersReducedMotion();

  return (
    <svg className="filter-defs" aria-hidden="true" focusable="false">
      {/*
        Область фільтра має запас під амплітуду зсуву: при scale={13}
        пікселі їдуть приблизно на ±6.5 одиниці, і без запасу край
        обрізало б.
      */}
      <filter id="livingOil" x="-12%" y="-12%" width="124%" height="124%">
        <feTurbulence
          type="fractalNoise"
          numOctaves={1}
          seed={7}
          baseFrequency="0.012 0.017"
          result="rawNoise"
        >
          {!reducedMotion && (
            <animate
              attributeName="baseFrequency"
              dur="14s"
              repeatCount="indefinite"
              values="0.0120 0.0170; 0.0134 0.0162; 0.0148 0.0154;
                      0.0160 0.0146; 0.0166 0.0138; 0.0158 0.0134;
                      0.0144 0.0142; 0.0130 0.0156; 0.0120 0.0170"
            />
          )}
        </feTurbulence>

        {/*
          Згладжування росте разом з амплітудою. Правило просте: що
          сильніший зсув, то помітніші сходинки растеризації, тому
          stdDeviation треба тримати приблизно на рівні scale/5.
        */}
        <feGaussianBlur in="rawNoise" stdDeviation="2.4" result="noise" />

        <feDisplacementMap
          in="SourceGraphic"
          in2="noise"
          scale={13}
          xChannelSelector="R"
          yChannelSelector="G"
        />
      </filter>
    </svg>
  );
}
